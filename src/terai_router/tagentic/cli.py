"""`terai tagentic`: run Tagentic (Tagentic1, beta) on a task, or open a session.

    terai tagentic "อ่าน README แล้วสรุป"            one task, then exit
    terai tagentic                                 session: the model greets first, then you chat and give tasks
    terai tagentic --init                          create User.md and Memory.md in the memory folder
    terai tagentic --init-context                  scaffold Userprompt.md, project/agent context, Docs/, Log/, Project/
    terai tagentic --show-memory                   show the four memory files in load order
    terai tagentic --setup                         download the Gemma 4 E2B weights

Relay mode (one command per turn, for a chat app that relays messages; prints one JSON object):

    terai tagentic --session NAME --start --json          new session, the model greets first
    terai tagentic --session NAME --message "TEXT" --json one user message
    terai tagentic --session NAME --approve | --deny      resume a write/edit/run that waits for the user
    terai tagentic --session NAME --reset                 delete the session

The session (history and a pending call) is stored in <memory folder>/sessions/NAME.json.

Writes, edits, code and shell runs ask before they run; --yes allows them all.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import time
from pathlib import Path
from typing import Callable, Optional

from . import memory as M
from .trace import Step

MODEL_NAME = 'Tagentic'
STATUS = 'Tagentic1, beta, prototype, not released'


def tuned_threads(cpus: Optional[int] = None) -> tuple:
    """(generation threads, batch/prefill threads) for llama.cpp on a shared VM.

    Measured on the 8-vCPU VM (2026-10-28): with all 8 threads, one generated token took 2-4 s, because the
    per-token barriers stall whenever any other process takes a core; with 6 it was ~18-24 tokens/s. Prefill was
    fastest with 7 (about 90 tokens/s against 55 with 8). Leave one or two cores free.
    """
    n = cpus or os.cpu_count() or 1
    if n <= 3:
        return n, n
    return n - 2, n - 1


def make_lm(args):
    """The local Gemma 4 model with the Tagentic settings (env TERAI_TAGENTIC_THREADS / _THREADS_BATCH override)."""
    from ..brain import local as L
    gen, batch = tuned_threads()
    gen = args.threads or int(os.environ.get('TERAI_TAGENTIC_THREADS') or 0) or gen
    batch = int(os.environ.get('TERAI_TAGENTIC_THREADS_BATCH') or 0) or (args.threads or batch)
    return L.LocalLM(model=args.model, threads=gen, threads_batch=batch, n_ctx=args.ctx, flash_attn=True)


def lm_key(args) -> tuple:
    """What makes two runs need the same loaded model (used by the persistent server)."""
    return (args.model, args.threads, args.ctx)


def make_confirm(yes: bool, stream_in=None, stream_out=None) -> Optional[Callable[[str, str], bool]]:
    if yes:
        return lambda tool, summary: True
    sin = stream_in or sys.stdin
    sout = stream_out or sys.stderr
    if not getattr(sin, 'isatty', lambda: False)():
        def deny(tool, summary):
            print(f'[{MODEL_NAME}] {tool} needs confirmation, but there is no terminal; denied (use --yes to allow).',
                  file=sout)
            return False
        return deny

    def ask(tool, summary):
        print(f'\n[{MODEL_NAME}] ขออนุญาต {tool}: {summary}', file=sout)
        sout.write('อนุญาตไหม [y/N] ')
        sout.flush()
        line = sin.readline()
        return line.strip().lower() in ('y', 'yes', 'ใช่', 'ตกลง', 'ok')
    return ask


class Session:
    """One chat session. Every reply is generated by the model; the session only keeps the conversation."""

    HISTORY_TURNS = 8   # earlier user/assistant pairs sent back to the model

    def __init__(self, agent, out=None) -> None:
        self.agent = agent
        self.out = out or sys.stdout
        self.history: list = []

    def _turn(self, text: str, shown: str):
        result = self.agent.run(text, history=self.history[-2 * self.HISTORY_TURNS:])
        self.history += [{'role': 'user', 'content': text}, {'role': 'assistant', 'content': result.final}]
        print(f'{shown}{result.final}', file=self.out)
        self.out.flush()
        return result

    def open(self):
        """The first turn: the model greets the user (asked with the [session_start] event)."""
        from .agent import SESSION_START
        return self._turn(SESSION_START, f'{MODEL_NAME}: ')

    def handle(self, line: str):
        line = (line or '').strip()
        if not line:
            return None
        return self._turn(line, f'\n{MODEL_NAME}: ')


# ------------------------------------------------------------------------------------------------ relay mode
SESSION_NAME = re.compile(r'^[A-Za-z0-9_.-]{1,64}$')
ARG_MAX = 200   # characters of a string argument kept in the relay JSON


def session_path(home, name: str) -> Path:
    if not SESSION_NAME.match(name or '') or name in ('.', '..'):
        raise ValueError(f'bad session name: {name!r} (letters, digits, _ . - only)')
    return Path(home).expanduser() / 'sessions' / f'{name}.json'


def load_session(path: Path) -> dict:
    if path.exists():
        return json.loads(path.read_text(encoding='utf-8'))
    return {'history': [], 'pending': None}


def save_session(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix('.tmp')
    tmp.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding='utf-8')
    os.replace(tmp, path)


def _clip_args(args: dict) -> dict:
    out = {}
    for k, v in (args or {}).items():
        out[k] = v if not isinstance(v, str) or len(v) <= ARG_MAX else v[:ARG_MAX] + f'... ({len(v)} chars)'
    return out


def relay_json(name: str, result, first_step: int, seconds: float, load_s: float) -> dict:
    steps = result.trace.steps[first_step:]
    pending = None
    if result.pending:
        pending = {'tool': result.pending['tool'], 'args': _clip_args(result.pending['args']),
                   'summary': result.pending['summary']}
    return {'model': MODEL_NAME, 'session': name,
            'trace': [{'think': s.think, 'tool': s.tool, 'args': _clip_args(s.args), 'result_short': s.note}
                      for s in steps],
            'answer': result.final if not result.pending else None,
            'pending_action': pending, 'stopped': result.stopped,
            'timing_s': round(seconds, 2), 'load_s': round(load_s, 2)}


def run_relay(args, home, factory, out) -> int:
    from .agent import SESSION_START

    def emit(obj: dict, rc: int = 0) -> int:
        print(json.dumps(obj, ensure_ascii=False), file=out)
        out.flush()
        return rc

    try:
        path = session_path(home, args.session)
    except ValueError as e:
        return emit({'session': args.session, 'error': str(e)}, 2)
    if args.reset:
        existed = path.exists()
        if existed:
            path.unlink()
        return emit({'session': args.session, 'reset': True, 'existed': existed})
    data = load_session(path)
    if args.start:
        data = {'history': [], 'pending': None}
    if (args.approve or args.deny) and not data.get('pending'):
        return emit({'session': args.session, 'error': 'nothing waits for approval in this session'}, 2)
    if args.message is not None and data.get('pending'):
        return emit({'session': args.session, 'error': 'a pending action waits: send --approve or --deny first',
                     'pending_action': {k: data['pending']['pending'][k] for k in ('tool', 'summary')}}, 2)
    if args.message is not None and not args.message.strip():
        return emit({'session': args.session, 'error': 'empty message'}, 2)

    t_load = time.monotonic()
    try:
        agent = factory()
        load = getattr(agent.lm, 'load', None)
        if load:
            load()
    except Exception as e:  # llama-cpp or the weights missing
        return emit({'session': args.session, 'error': f'{type(e).__name__}: {e}'}, 1)
    load_s = time.monotonic() - t_load

    agent.tools.relay = True   # a gated call stops the turn with pending_action instead of asking on a terminal

    t0 = time.monotonic()
    try:
        if args.approve or args.deny:
            state = data['pending']
            first = len(state.get('steps') or [])
            result = agent.resume(state, approved=bool(args.approve))
            task = state['task']
        else:
            task = SESSION_START if args.start else args.message.strip()
            first = 0
            hist = data['history'][-2 * Session.HISTORY_TURNS:]
            result = agent.run(task, history=hist)
    except Exception as e:
        return emit({'session': args.session, 'error': f'{type(e).__name__}: {e}'}, 1)
    seconds = time.monotonic() - t0
    if result.pending:
        data['pending'] = result.state
    else:
        data['pending'] = None
        data['history'] += [{'role': 'user', 'content': task}, {'role': 'assistant', 'content': result.final}]
    save_session(path, data)
    if args.trace_file:
        result.trace.write(args.trace_file)
    return emit(relay_json(args.session, result, first, seconds, load_s))


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(prog='terai tagentic',
                                 description=f'{MODEL_NAME} ({STATUS}): thinking + agentic model on local Gemma 4 E2B.')
    ap.add_argument('task', nargs='*', help='the task; leave out to open a session')
    ap.add_argument('--workspace', '-w', default=None, help='root folder for every file tool (default: current folder)')
    ap.add_argument('--yes', '-y', action='store_true', help='allow writes, edits, code and shell runs without asking')
    ap.add_argument('--max-steps', type=int, default=12)
    ap.add_argument('--timeout', type=float, default=600.0, help='seconds per task (default 600)')
    ap.add_argument('--tool-timeout', type=float, default=60.0, help='seconds per run_python/run_shell (default 60)')
    ap.add_argument('--memory-dir', default=None, help='memory folder (default $TERAI_TAGENTIC_HOME or ~/.terai/tagentic)')
    ap.add_argument('--trace-file', default=None, help='append the trace as JSON lines to this file')
    ap.add_argument('--json', action='store_true', help='print the result as one JSON object')
    ap.add_argument('--model', default=None, help='Gemma 4 size (default e2b)')
    ap.add_argument('--threads', type=int, default=None)
    ap.add_argument('--ctx', type=int, default=8192, help='context length (default 8192)')
    ap.add_argument('--init', action='store_true', help='create User.md and Memory.md, then exit')
    ap.add_argument('--init-context', action='store_true', help='create workspace context files/folders without overwriting, then exit')
    ap.add_argument('--show-memory', action='store_true', help='print the four memory files in load order, then exit')
    ap.add_argument('--setup', action='store_true', help='download the Gemma 4 weights, then exit')
    ap.add_argument('--session', default=None, help='relay mode: session name (stored under <memory folder>/sessions)')
    rel = ap.add_mutually_exclusive_group()
    rel.add_argument('--start', action='store_true', help='relay mode: new session, the model greets first')
    rel.add_argument('--message', default=None, help='relay mode: one user message')
    rel.add_argument('--approve', action='store_true', help='relay mode: allow the call that waits')
    rel.add_argument('--deny', action='store_true', help='relay mode: refuse the call that waits')
    rel.add_argument('--reset', action='store_true', help='relay mode: delete the session')
    return ap


def main(argv=None, lm=None, stdin=None, stdout=None) -> int:
    """``lm`` is a test hook (a LocalLM with a client)."""
    args = build_parser().parse_args(argv)
    out = stdout or sys.stdout
    sin = stdin or sys.stdin
    home = args.memory_dir or M.default_home()

    if args.init:
        made = M.init_home(home)
        print('\n'.join(f'created {p}' for p in made) or f'already there: {home}', file=out)
        return 0
    if args.show_memory:
        for f in M.load_memory(home):
            print(f'===== {f.name} ({f.source}: {f.path}, {len(f.text)} characters) =====\n{f.text}\n', file=out)
        return 0
    if args.setup:
        from ..brain import local as L
        for p in L.setup(args.model or L.DEFAULT_MODEL, vision=False):
            print(p, file=out)
        return 0

    from .workspace import SandboxError, Workspace
    try:
        ws = Workspace(args.workspace)
    except SandboxError as e:
        print(f'{MODEL_NAME}: {e}', file=sys.stderr)
        return 2
    if args.init_context:
        from .context import init_context
        created, existing = init_context(ws)
        for name in created:
            print(f'created {ws.root / name}', file=out)
        for name in existing:
            print(f'already exists (unchanged) {ws.root / name}', file=out)
        if not created and not existing:
            print(f'context folders already ready: {ws.root}', file=out)
        return 0

    from .agent import Tagentic
    from .tools import Toolbox
    trace_out = sys.stderr if args.json else out

    def on_step(step: Step) -> None:
        print('  · ' + step.compact(), file=trace_out)
        trace_out.flush()

    def factory():
        model = lm if lm is not None else make_lm(args)
        box = Toolbox(ws, home=home, confirm=make_confirm(args.yes, sin), yes=args.yes,
                      tool_timeout=args.tool_timeout)
        return Tagentic(model, box, home=home, max_steps=args.max_steps, timeout=args.timeout, on_step=on_step)

    M.init_home(home)
    relay = args.start or args.message is not None or args.approve or args.deny or args.reset
    if relay or args.session:
        if not (args.session and relay):
            print(f'{MODEL_NAME}: relay mode needs --session NAME and one of --start/--message/--approve/--deny/--reset',
                  file=sys.stderr)
            return 2
        return run_relay(args, home, factory, out)
    task = ' '.join(args.task).strip()
    try:
        agent = factory()
        if not task:
            load = getattr(agent.lm, 'load', None)
            if load:
                load()
    except Exception as e:  # llama-cpp or the weights missing
        print(f'{MODEL_NAME}: {type(e).__name__}: {e}', file=sys.stderr)
        return 1

    if task:
        try:
            result = agent.run(task)
        except Exception as e:  # llama-cpp or the weights missing
            print(f'{MODEL_NAME}: {type(e).__name__}: {e}', file=sys.stderr)
            return 1
        if args.trace_file:
            result.trace.write(args.trace_file)
        if args.json:
            print(json.dumps({'model': MODEL_NAME, 'status': STATUS, 'final': result.final,
                              'stopped': result.stopped, 'steps': [s.to_dict() for s in result.trace.steps]},
                             ensure_ascii=False), file=out)
        else:
            print(f'\n{MODEL_NAME}: {result.final}', file=out)
        return 0

    # session: the model is loaded, then it greets first
    sess = Session(agent, out)
    try:
        result = sess.open()
    except Exception as e:
        print(f'{MODEL_NAME}: {type(e).__name__}: {e}', file=sys.stderr)
        return 1
    if args.trace_file:
        result.trace.write(args.trace_file)
    while True:
        try:
            out.write('\n> ')
            out.flush()
            line = sin.readline()
        except KeyboardInterrupt:
            break
        if not line or line.strip() in ('/exit', '/quit'):
            break
        try:
            result = sess.handle(line)
        except KeyboardInterrupt:
            continue
        if args.trace_file and result is not None:
            result.trace.write(args.trace_file)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
